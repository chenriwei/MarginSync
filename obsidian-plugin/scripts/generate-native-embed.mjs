/**
 * 把 prebuilds/<platform>/nmv-<N>/better_sqlite3.node 编成 TS 常量。
 * 运行时按 process.versions.modules 选择匹配的 ABI。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(fileURLToPath(import.meta.url), "..", "..");
const prebuildsDir = path.join(root, "prebuilds");
const outFile = path.join(root, "src", "native-embed.generated.ts");

/** @type {Record<string, Record<string, string>>} */
const embed = {};

if (fs.existsSync(prebuildsDir)) {
  for (const platform of fs.readdirSync(prebuildsDir)) {
    const platformDir = path.join(prebuildsDir, platform);
    if (!fs.statSync(platformDir).isDirectory()) continue;

    for (const entry of fs.readdirSync(platformDir)) {
      let nmv = null;
      let nodeFile = null;

      if (entry.startsWith("nmv-")) {
        nmv = entry.slice(4);
        nodeFile = path.join(platformDir, entry, "better_sqlite3.node");
      } else if (entry === "better_sqlite3.node") {
        // 旧布局兼容：prebuilds/darwin-arm64/better_sqlite3.node → 当作 nmv-140
        nmv = "140";
        nodeFile = path.join(platformDir, entry);
      }

      if (!nmv || !nodeFile || !fs.existsSync(nodeFile)) continue;
      if (!embed[platform]) embed[platform] = {};
      embed[platform][nmv] = fs.readFileSync(nodeFile).toString("base64");
      console.log(`embedded ${platform}/nmv-${nmv}: ${fs.statSync(nodeFile).size} bytes`);
    }
  }
}

if (!Object.keys(embed).length) {
  console.warn("warning: no prebuilds found — Obsidian 安装包将无法读取 SQLite");
}

const header = `/** AUTO-GENERATED by scripts/generate-native-embed.mjs — do not edit */\n`;
fs.writeFileSync(
  outFile,
  `${header}export const NATIVE_EMBED: Record<string, Record<string, string>> = ${JSON.stringify(embed)};\n`
);
console.log(`wrote ${outFile}`);
